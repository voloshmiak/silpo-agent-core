def build_plan_prompt(
    *,
    weight_kg: float,
    target_weight_kg: float,
    budget_uah: float,
    goal: Goal | None = None,
    weekly_pace_kg: float = 0.0,
    workouts_per_week: int = 0,
    workout_schedule: dict[str, str] | None = None,
    height_cm: float | None = None,
    age: int | None = None,
    sex: Sex | None = None,
    diet_type: DietType = "none",
    allergens: list[str] | None = None,
    excluded_products: list[str] | None = None,
    promo_priority: PromoPriority = "medium",
    delivery_included: bool = True,
    fridge_items: list[str] | None = None,
    note: str = "",
    previous_plan: dict[str, Any] | None = None,
    previous_feedback: WeekFeedback | None = None,
) -> str:
    goal = goal or goal_from_weights(weight_kg, target_weight_kg)
    lines = [
        f"Поточна вага: {weight_kg} кг. Цільова вага: {target_weight_kg} кг. Ціль: {goal}.",
    ]
    if height_cm:
        lines.append(f"Зріст: {height_cm} см.")
    if age:
        lines.append(f"Вік: {age} років.")
    if sex:
        lines.append(f"Стать: {sex}.")
    if weekly_pace_kg and goal != "maintain":
        lines.append(
            f"Обраний темп: {weekly_pace_kg} кг/тиждень — передай його у calc_targets "
            "як weekly_pace_kg і не виводь темп самостійно з різниці ваг."
        )

    lines.append(f"Тренувань на тиждень: {workouts_per_week}.")
    if workout_schedule:
        listed = "; ".join(
            f"{WEEKDAY_LABELS[day]} ({day}) — {workout_schedule[day] or 'тренування'}"
            for day in DAYS
            if day in workout_schedule
        )
        lines.append(
            f"Розклад тренувань: {listed}. Саме цим дням постав workout: true і додай "
            "вуглеводів та білка; решті — workout: false і менше вуглеводів."
        )
    if diet_type != "none":
        rule = DIET_RULES.get(diet_type)
        label = DIET_LABELS.get(diet_type, diet_type)
        lines.append(
            f"Тип дієти: {label}"
            + (f" — {rule}" if rule else "")
            + ". Це жорстке обмеження і для раціону, і для кошика."
        )
    if allergens:
        lines.append(
            f"Алергени, жорстка заборона (разом із прихованими джерелами у складі): "
            f"{', '.join(allergens)}."
        )
    if excluded_products:
        lines.append(f"Просив не додавати: {', '.join(excluded_products)}.")
    if diet_type != "none" or allergens or excluded_products:
        lines.append(
            "Ці обмеження додаються до тих, що поверне silpo_get_my_food_restrictions, "
            "і разом ідуть у summary.restrictions."
        )

    lines.append(f"Бюджет на тиждень: {budget_uah} грн.")
    if delivery_included:
        lines.append(
            "Доставка входить у бюджет: summary.remaining_uah = бюджет мінус "
            "summary.total_uah (тобто разом із доставкою)."
        )
    else:
        lines.append(
            "Доставка оплачується окремо і в бюджет не входить: summary.remaining_uah = "
            "бюджет мінус summary.products_total_uah. Саму доставку все одно поверни у "
            "summary.delivery_uah."
        )
    lines.append(PROMO_RULES.get(promo_priority, PROMO_RULES["medium"]))

    if fridge_items:
        lines.append(f"Вдома вже є: {', '.join(fridge_items)}.")
    if note:
        lines.append(
            f"Додатково від користувача: {note}. Це прямі побажання. Назване тут "
            "закладай у раціон і кошик ПЕРШИМ, ще до того, як добиратимеш решту "
            "продуктів, і плануй бюджет уже навколо цього. Пропустити побажання можна "
            "лише тоді, коли продукт порушує обмеження або його немає в наявності — і "
            "тоді напиши в summary.notes, яке саме і чому. «Не вистачило бюджету» "
            "поясненням не є: бюджет розподіляєш ти, і побажання йде в нього першим."
        )
    if previous_feedback:
        lines += _feedback_lines(previous_feedback)
    elif previous_plan:
        lines += _previous_plan_digest(previous_plan)
    lines.append("Склади раціон на тиждень і збери кошик.")
    return "\n".join(lines)


def _feedback_lines(feedback: WeekFeedback) -> list[str]:
    lines = ["Минулий тиждень — що справді сталося (спирайся на це, а не на здогади):"]
    head = []
    if feedback.spent_uah:
        head.append(f"витрачено {feedback.spent_uah} грн")
    if feedback.weight_change_kg:
        head.append(f"зміна ваги {feedback.weight_change_kg:+g} кг")
    if head:
        lines.append("- " + ", ".join(head) + ".")

    for verdict, label in VERDICT_LABELS.items():
        named = [
            product.name + (f" ({product.note})" if product.note else "")
            for product in feedback.products
            if product.verdict == verdict and product.name
        ]
        if named:
            lines.append(f"- {label}: {'; '.join(named)}.")

    rated = [dish for dish in feedback.dishes if dish.title and (dish.rating or dish.note)]
    if rated:
        listed = "; ".join(
            f"«{dish.title}»"
            + (f" {dish.rating}/5" if dish.rating else "")
            + (f" — {dish.note}" if dish.note else "")
            for dish in rated
        )
        lines.append(f"- Страви: {listed}.")
    if feedback.note:
        lines.append(f"- {feedback.note}")

    lines.append(
        "Повтори те, що зайшло, прибери те, що не зайшло, і не бери повторно того, що "
        "лишилось. Товари однаково шукай заново — ціни й наявність змінились."
    )
    return lines


def _unwrap_plan(plan: dict[str, Any]) -> dict[str, Any]:
    if plan.get("cart") or plan.get("days"):
        return plan
    for key in ("plan_data", "plan", "content"):
        nested = plan.get(key)
        if isinstance(nested, dict) and (nested.get("cart") or nested.get("days")):
            log.info("previous_plan arrived wrapped in %r, unwrapping", key)
            return nested
    return plan


def _previous_plan_digest(plan: dict[str, Any]) -> list[str]:
    plan = _unwrap_plan(plan)
    cart = [str(item.get("name") or "").strip() for item in (plan.get("cart") or [])]
    cart = [name for name in cart if name]

    titles: list[str] = []
    for day in plan.get("days") or []:
        for key in MEAL_KEYS:
            title = str((day.get(key) or {}).get("title") or "").strip()
            if title and title not in titles:
                titles.append(title)

    if not cart and not titles:
        log.warning("previous_plan has no cart and no dishes — leaving it out of the prompt")
        return []

    lines = ["Минулого тижня (стисла вижимка з архіву, не джерело товарів і цін):"]
    if cart:
        lines.append(f"- Купували: {', '.join(cart)}.")
    if titles:
        lines.append(f"- Готували: {'; '.join(titles)}.")
    spent = (plan.get("summary") or {}).get("total_uah")
    if spent:
        lines.append(f"- Витратили {spent} грн.")
    lines.append(
        "Це підказка про смаки, а не готовий кошик: кожен товар шукай заново через "
        "silpo_find_products_batch, ціни й наявність за тиждень змінились."
    )
    log.info("previous_plan digested to %d products and %d dishes", len(cart), len(titles))
    return lines


def goal_from_weights(weight_kg: float, target_weight_kg: float) -> Goal:
    if target_weight_kg < weight_kg:
        return "lose"
    if target_weight_kg > weight_kg:
        return "gain"
    return "maintain"
